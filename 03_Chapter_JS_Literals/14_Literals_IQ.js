let count = 10; // number literal
let negativeCount = -5; // number literal
let pi = 3.14; // number literal
let zero = 0; // number literal

let hexa = 0xFF; // hexadecimal number literal
console.log(hexa); // Output: 255
console.log(typeof hexa); // Output: number

let color_code = 0xFF5733; // hexadecimal number literal
console.log(color_code); // Output: 16753203
console.log(typeof color_code); // Output: number

let binary = 0b1010; // binary number literal
console.log(binary); // Output: 10
console.log(typeof binary); // Output: number

let octal = 0o12; // octal number literal
console.log(octal); // Output: 10
console.log(typeof octal); // Output: number

let million = 1e6; // exponential number literal
console.log(million); // Output: 1000000
console.log(typeof million); // Output: number

let tiny = 1.5e-4; // exponential number literal
console.log(tiny); // Output: 0.00015
console.log(typeof tiny); // Output: number
