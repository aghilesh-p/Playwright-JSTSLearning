// For loop - Repeat a block of code

/* syntax

for(i;c;u){

}

i - initialization
c - condition
u - updation */

for (let i = 0; i < 10; i++) {
    console.log(i);
}

console.log("----------------------------------------");

for (let j = 20; j <= 30; j++) {
    console.log(j);
}

console.log("----------------------------------------");

for (let k = 50; k <= 60; ++k) {
    console.log(k);
}