let num = [10, 20, 30, 40];
console.log(num.length);        // gives length of array

console.log(num[3]);            // gives the value of 3rd array
console.log(num.at(3));         // +ive value given in .at() gives the value of array
                                // based on +ive index

console.log(num.at(-3));        // -ive value given in .at() gives the value of array
                                // based on -ive index