// While loop - same as for loop
// ICU

let i = 0;          // I - Initialization
while (i < 10) {    // C - Condition
    console.log(i);
    i++;            // U - Updation
}

//same as for loop

for (let j = 10; j < 20; j++) {
    console.log(j);
}

// for loop can also be like this 
// but we wont use this - its not a good practice

