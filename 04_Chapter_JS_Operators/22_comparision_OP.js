// Compasion Operator (will always result in the boolean, true or false)

// = - Assignment Operator


//  ==, ===  - Comparision Operator

// == -> loose comparision
// pizza == pizza (value type)
// == Loose check we will check either value or data type.

// === -> strict comparision
// dominoz === pizzahut (value type & data type)
// === Strict check we will check for both the datatype and value


// > , < , >= , <=

console.log(3 > 4);
console.log(3 < 4);
console.log(4 >= 4);
console.log(4 <= 3);

console.log(typeof 5);
console.log(typeof "5");

console.log(5 == "5"); // loose comparision
console.log(5 == 5);

console.log(5 === "5"); // strict comparision
console.log(5 === 5);

// ! -> not char

console.log(5 != "5"); // loose comparision - compares value
console.log(5 !== "5"); // strict comparision - compares value & data
