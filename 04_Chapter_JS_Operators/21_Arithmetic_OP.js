// Arithmetic operator
// +,-,*,/,%

// Assignment operator

let x = 10;
let y = 3;

// Arithmetic operator

let sum = x + y; // addition
let sub = x - y; // subtraction
let mul = x * y; // multiplication
let div = x / y; // division
let mod = x % y; // modulus

console.log(sum);
console.log(sub);
console.log(mul);
console.log(div);
console.log(mod);

//  n%2 == 1 - odd number,  n%2 == 0 - even number
console.log(101 % 2);
console.log(100 % 2);

// Exponential **

console.log(x ** y); // x^y -> 10^3 => 10*10=100 -> 100*10=1000
console.log(2 ** 4); // 2^4 => 16